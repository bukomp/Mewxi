//! Composable status line.
//!
//! The one-line ANSI string Claude Code shows (rendered by `mewxi
//! status`) is built from reorderable **blocks** instead of one hardcoded
//! format. Built-in defaults are embedded from the repo `blocks/` folder
//! (see `build.rs`); users override them by id, or add their own, by
//! dropping `*.toml` files in their `status_blocks_dir` (config). The
//! order + enabled set comes from `status_blocks` in `accounts.toml`.
//!
//! With no user config the default set reproduces the legacy line
//! byte-for-byte — see the golden tests in [`crate::watch`].

